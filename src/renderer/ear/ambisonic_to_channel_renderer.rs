/// Returns the number of active Ambisonic channels `(order + 1)^2` and the order normalization
/// scale factor for `in_order`.
///
/// # Parameters
/// * `in_order`: Input Ambisonic order.
/// * `scales`: Per-layout normalization factors for `[Zoa, Order1, Order2, Order3]`.
fn order_channels_and_scale(in_order: HighOrderAmbisonics, scales: &[f32; 4]) -> (usize, f32) {
    let scale = match in_order {
        HighOrderAmbisonics::Zoa => scales[0],
        HighOrderAmbisonics::Order1 => scales[1],
        HighOrderAmbisonics::Order2 => scales[2],
        HighOrderAmbisonics::Order3 => scales[3],
        HighOrderAmbisonics::Order4 => 1.0,
    };
    (in_order.channels().get() as usize, scale)
}

/// Mixes the first `m` columns of `base_Ambi4O` speaker rows into `out_mat[..n * m]` according to
/// sparse `row_mix` entries and [`CHAN_TO_CHAN_GAIN_LOOKUP`] weights.
///
/// # Parameters
/// * `base_Ambi4O`: Base 4th-order (`Ambi4O`) matrix with row stride [`Ambi4O_ACN_CHANNELS`].
/// * `row_mix`: Sparse `(base_row, out_row, lookup_idx)` entries indexing into
///   [`CHAN_TO_CHAN_GAIN_LOOKUP`].
/// * `m`: Number of active input Ambisonic channels (`1..=25`).
/// * `n`: Number of target non-LFE output speaker rows (`1..=16`).
/// * `out_mat`: Destination slice of length at least `n * m`, zero-initialized before accumulation.
fn mix_derived_ambi_to_chan_rows(
    base_Ambi4O: &[f32],
    row_mix: &[SparseMatrixEntry],
    m: usize,
    n: usize,
    out_mat: &mut [f32],
) {
    let Some(out_slice) = out_mat.get_mut(..n * m) else {
        return;
    };
    out_slice.fill(0.0);
    for &entry in row_mix {
        let base_row = entry.in_ch();
        let out_row = entry.out_ch();
        let src_start = base_row * Ambi4O_ACN_CHANNELS;
        let dst_start = out_row * m;
        if out_row < n
            && let Some(&weight) = CHAN_TO_CHAN_GAIN_LOOKUP.get(entry.lookup_idx())
            && let Some(src_row) = base_Ambi4O.get(src_start..src_start + m)
            && let Some(dst_row) = out_slice.get_mut(dst_start..dst_start + m)
        {
            simd_utils::scalar_multiply_and_accumulate(weight, src_row, dst_row);
        }
    }
}

/// Retrieves the HOA-to-multichannel conversion matrix for a given input HOA order and output
/// speaker layout.
///
/// Port of `IAMF_element_renderer_get_H2M_matrix`.
///
/// # Parameters
/// * `in_order`: Order of the input ambisonic sound field.
/// * `out_system`: Target output layout.
pub fn element_renderer_get_ambi_to_chan_matrix(
    in_order: HighOrderAmbisonics,
    out_system: OutputLayout,
) -> Result<AmbisonicToChannelRenderer, OarError> {
    for entry in AMBI_TO_CHAN_LAYOUT_TAB.iter() {
        if entry.out_system == out_system {
            let (m, scale) = order_channels_and_scale(in_order, &entry.scales);
            let n = entry.n as usize;
            let mut derived_mat = [0.0f32; MAX_DERIVED_AMBI_TO_CHAN_ELEMENTS];
            let has_derived_mat = if let Some(row_mix) = entry.row_mix {
                mix_derived_ambi_to_chan_rows(entry.base_Ambi4O, row_mix, m, n, &mut derived_mat);
                true
            } else {
                false
            };
            return Ok(AmbisonicToChannelRenderer {
                in_order,
                out_system: entry.out_system,
                channels: entry.channels as usize,
                lfe1: entry.lfe1 as i32,
                lfe2: entry.lfe2 as i32,
                mat: entry.base_Ambi4O,
                scale,
                derived_mat,
                has_derived_mat,
                m,
                n,
            });
        }
    }
    Err(OarError::NotSupported)
}

/// Renders HOA input signals into direct speaker output channels.
///
/// Port of `IAMF_element_renderer_render_H2M`. Handles channel remapping for LFE slots
/// and zeroes out LFE channels as HOA LFE filtering is disabled (`DISABLE_LFE_HOA == 1`).
///
/// # Parameters
/// * `ambi_to_chan_matrix`: Conversion matrix configuration obtained via
///   [`element_renderer_get_ambi_to_chan_matrix`].
/// * `inputs`: Validated planar input channel buffer ([`PlanarBufferRef`]).
/// * `outputs`: Validated mutable planar output channel buffer ([`PlanarBufferMut`]).
pub fn element_renderer_render_ambi_to_chan(
    ambi_to_chan_matrix: &AmbisonicToChannelRenderer,
    inputs: PlanarBufferRef<'_, '_>,
    outputs: &mut PlanarBufferMut<'_, '_>,
) -> Result<(), OarError> {
    if inputs.num_channels() != ambi_to_chan_matrix.m
        || outputs.num_channels() != ambi_to_chan_matrix.channels
        || outputs.num_samples() != inputs.num_samples()
        || ambi_to_chan_matrix.m > Ambi4O_ACN_CHANNELS
    {
        return Err(OarError::InvalidParameter);
    }

    let num_non_lfe_channels = ambi_to_chan_matrix.n;
    let lfe1_index = ambi_to_chan_matrix.lfe1;
    let lfe2_index = ambi_to_chan_matrix.lfe2;

    let (weights, out_stride) = if ambi_to_chan_matrix.has_derived_mat {
        let len = ambi_to_chan_matrix.n * ambi_to_chan_matrix.m;
        let Some(derived) = ambi_to_chan_matrix.derived_mat.get(..len) else {
            return Err(OarError::InvalidParameter);
        };
        (derived, ambi_to_chan_matrix.m)
    } else {
        (ambi_to_chan_matrix.mat, Ambi4O_ACN_CHANNELS)
    };
    let mv = MatrixView {
        data: MatrixData::Dense { weights, scale: ambi_to_chan_matrix.scale },
        in_dim: ambi_to_chan_matrix.m,
        in_stride: 1,
        out_dim: ambi_to_chan_matrix.n,
        out_stride,
        in_idx_map: None,
    };
    matrix_render(&mv, inputs, outputs)?;

    if lfe1_index >= 0 || lfe2_index >= 0 {
        let mut map = [0usize; MAX_OUTPUT_CHANNEL_COUNT];
        let mut chan_i = 0usize;
        for i in 0..num_non_lfe_channels {
            // Skip LFE channels.
            while chan_i as i32 == lfe1_index || chan_i as i32 == lfe2_index {
                chan_i += 1;
            }
            if i < map.len() {
                map[i] = chan_i;
            }
            chan_i += 1;
        }
        let nsamples = inputs.num_samples();
        let num_out_channels = outputs.num_channels();
        let mut out_slices: [&mut [f32]; MAX_OUTPUT_CHANNEL_COUNT] =
            std::array::from_fn(|_| &mut [] as &mut [f32]);
        let out_slices_ref = &mut out_slices[..num_out_channels];
        outputs.as_slices_mut(out_slices_ref);
        // Iterate backwards from the highest channel index to 0. When right-shifting slices across
        // the planar output buffer (`out_slices_ref[dest_idx] = out_slices_ref[i]`), reverse
        // iteration guarantees higher destination slots are populated before lower channels
        // can overwrite them.
        for i in (0..num_non_lfe_channels).rev() {
            let dest_idx = *map.get(i).unwrap_or(&i);
            if dest_idx != i && dest_idx < out_slices_ref.len() && i < out_slices_ref.len() {
                if dest_idx > i {
                    let (left, right) = out_slices_ref.split_at_mut(dest_idx);
                    if let Some(src_slice) = left.get(i)
                        && let Some(dst_slice) = right.get_mut(0)
                    {
                        dst_slice[..nsamples].copy_from_slice(&src_slice[..nsamples]);
                    }
                } else {
                    let (left, right) = out_slices_ref.split_at_mut(i);
                    if let Some(src_slice) = right.first()
                        && let Some(dst_slice) = left.get_mut(dest_idx)
                    {
                        dst_slice[..nsamples].copy_from_slice(&src_slice[..nsamples]);
                    }
                }
            }
        }

        if lfe1_index >= 0 && (lfe1_index as usize) < out_slices_ref.len() {
            let lfe_slice = &mut out_slices_ref[lfe1_index as usize];
            lfe_slice[..nsamples].fill(0.0);
        }
        if lfe2_index >= 0 && (lfe2_index as usize) < out_slices_ref.len() {
            let lfe_slice = &mut out_slices_ref[lfe2_index as usize];
            lfe_slice[..nsamples].fill(0.0);
        }
    }

    Ok(())
}

